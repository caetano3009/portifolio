
DROP TABLE TRANSACOES CASCADE CONSTRAINTS;
DROP TABLE CONTAS CASCADE CONSTRAINTS;
DROP TABLE USUARIOS CASCADE CONSTRAINTS;

CREATE TABLE USUARIOS (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(100),
    EMAIL VARCHAR2(100),
    SENHA VARCHAR2(100)
);

CREATE TABLE CONTAS (
    ID_CONTA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO NUMBER,
    SALDO NUMBER(10,2),

    CONSTRAINT FK_CONTA_USUARIO
    FOREIGN KEY (ID_USUARIO)
    REFERENCES USUARIOS(ID_USUARIO)
);

CREATE TABLE TRANSACOES (
    ID_TRANSACAO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CONTA NUMBER,
    TIPO VARCHAR2(20),
    VALOR NUMBER(10,2),

    CONSTRAINT FK_TRANSACAO_CONTA
    FOREIGN KEY (ID_CONTA)
    REFERENCES CONTAS(ID_CONTA)
);

